#!/bin/bash

# ROS_DISTRO is already set by the base ROS Docker image
# If for some reason it's not set, fall back to jazzy
ROS_DISTRO="${ROS_DISTRO:-jazzy}"

# Creates required temp directory for GUI applications - needed by Linux desktop standards
# Set up XDG runtime directory
export XDG_RUNTIME_DIR=/tmp/runtime-$USER
mkdir -p $XDG_RUNTIME_DIR
chmod 700 $XDG_RUNTIME_DIR

# Set base paths for convenience
# ROS_WS is the path to the ROS 2 workspace
ROS_WS="/root/warehouse_ws"

# SHARED_ROS2 is the path to shared ROS 2 files
SHARED_ROS2="/root/shared/ros2"

# Create ros_domain_id.txt file with default value 0 if it doesn't exist
# This file stores the ROS_DOMAIN_ID, which is used for multi-robot communication
ROS_DOMAIN_ID_FILE="$SHARED_ROS2/ros_domain_id.txt"

if [ ! -f "$ROS_DOMAIN_ID_FILE" ]; then
    # If the file doesn't exist, create it with a default value of 0
    echo "0" > "$ROS_DOMAIN_ID_FILE"
    echo "Created $ROS_DOMAIN_ID_FILE with default value 0"
fi

# The ROS_DOMAIN_ID will need to be the same for computers that you want to communicate with each other.
# This value can take any number between [0,232]. It is useful if you have multiple robots in the same environment.
# Update .bashrc with ROS_DOMAIN_ID if it does not already exist
if ! grep -q "export ROS_DOMAIN_ID" /root/.bashrc; then
  # Read the ROS_DOMAIN_ID from the file
  ros_domain_id=$(cat "$ROS_DOMAIN_ID_FILE")
  # Add the export command to .bashrc if it's not already there
  echo "export ROS_DOMAIN_ID=$ros_domain_id" >> /root/.bashrc
fi

# Make the ROS Domain ID available to the current script
# This allows the current script to use the ROS_DOMAIN_ID
export ROS_DOMAIN_ID=$(cat "$ROS_DOMAIN_ID_FILE")

# Source ROS setup file
# This sets up the ROS 2 environment for the current shell session
source /opt/ros/$ROS_DISTRO/setup.bash

# Source the local workspace setup
source $ROS_WS/install/setup.bash

# Source the .bashrc file to ensure all environment variables are up to date
source /root/.bashrc

# Change to the ROS 2 workspace directory
cd $ROS_WS

# Build the ROS 2 workspace using colcon
colcon build --symlink-install

# Change back to the root directory
cd

# Source .bashrc again to ensure any changes made during the build are applied
source /root/.bashrc

# Set up Clearpath robot config
# /root/clearpath is a container-internal directory generated by the clearpath generators below
mkdir -p /root/clearpath
ln -sf $ROS_WS/src/warehouse_sim/config/husky_transport.yaml /root/clearpath/robot.yaml

# Run all three Clearpath generators
# generate_description creates robot.urdf.xacro which is needed for SDF conversion below
ros2 run clearpath_generator_common generate_bash -s /root/clearpath
ros2 run clearpath_generator_common generate_description -s /root/clearpath
ros2 run clearpath_generator_gz generate_launch -s /root/clearpath
ros2 run clearpath_generator_gz generate_param -s /root/clearpath

# Source Clearpath setup
source /root/clearpath/setup.bash
if ! grep -q "source /root/clearpath/setup.bash" /root/.bashrc; then
    echo "source /root/clearpath/setup.bash" >> /root/.bashrc
fi

# Pre-convert robot URDF to SDF with absolute mesh paths
# This fixes the model:// URI resolution issue in Gazebo at spawn time
echo "Pre-converting robot URDF to SDF with absolute paths..."

# Verify the xacro file was generated successfully by the generators above
if [ ! -f /root/clearpath/robot.urdf.xacro ]; then
    echo "ERROR: /root/clearpath/robot.urdf.xacro not found."
    echo "       Did the clearpath generators run successfully above?"
    exit 1
fi

# Convert xacro to URDF
ros2 run xacro xacro /root/clearpath/robot.urdf.xacro \
    is_sim:=true \
    namespace:=a200_0001 \
    gazebo_controllers:=/root/clearpath/platform/config/control.yaml \
    > /tmp/robot_abs.urdf

if [ ! -s /tmp/robot_abs.urdf ]; then
    echo "ERROR: xacro conversion produced an empty URDF. Check your robot.urdf.xacro."
    exit 1
fi

# Convert URDF to SDF 
gz sdf -p /tmp/robot_abs.urdf > /tmp/robot_abs.sdf
if [ ! -s /tmp/robot_abs.sdf ]; then
    echo "ERROR: gz sdf conversion produced an empty SDF. Check your URDF."
    exit 1
fi

# Replace model://clearpath_* URIs with absolute paths so Gazebo can find meshes.
# Covers every Clearpath description package the robot uses (platform,
# sensors such as the lidar, ...). ros2 pkg prefix resolves the share root
# regardless of ROS distro.
ROS_SHARE_PATH=$(ros2 pkg prefix clearpath_platform_description)/share
sed -i -E "s|model://(clearpath_[a-z_]+)|${ROS_SHARE_PATH}/\1|g" /tmp/robot_abs.sdf
if grep -q "model://" /tmp/robot_abs.sdf; then
    echo "WARNING: unresolved model:// URIs remain in /tmp/robot_abs.sdf:"
    grep -o "model://[^<]*" /tmp/robot_abs.sdf | sort -u
fi

echo "SDF ready at /tmp/robot_abs.sdf"

# Any command you run after this script runs in the environment set up by the script.
exec "$@"